    private void setupLogger() {
        // Проверяем существование файла логов
        File logFile = new File(LOG_FILE);
        if (!logFile.exists()) {
            try {
                logFile.createNewFile();
            } catch (IOException e) {
                logger.error("Could not create log file", e);
            }
        }
    }
    private void connectToServer() {
        try {
            socket = new Socket("localhost", 12345);
            out = new PrintWriter(socket.getOutputStream(), true);
            in = new BufferedReader(new InputStreamReader(socket.getInputStream()));

            jTextArea1.append("Connected to server.\n");
            jTextArea1.append("Enter expressions in format: <number> <operator> <number>\n");
            jTextArea1.append("Supported operators: + - * /\n");
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Connection error: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            logger.error("Connection error", e);
        }
    }

    private void logAction(String message) {
        String timestamp = LocalDateTime.now().format(dtf);
        String logMessage = timestamp + " - " + message;

        jTextArea1.append(logMessage + "\n");

        logger.info(message);

        if (logToFile) {
            try {
                Files.write(Paths.get(LOG_FILE),
                        (logMessage + "\n").getBytes(),
                        StandardOpenOption.APPEND);
            } catch (IOException e) {
                logger.error("Failed to write to log file", e);
            }
        }
    }

    private void logError(String error) {
        String timestamp = LocalDateTime.now().format(dtf);
        String logMessage = timestamp + " - ERROR: " + error;

        jTextArea1.append(logMessage + "\n");

        logger.error(error);

        if (logToFile) {
            try {
                Files.write(Paths.get(LOG_FILE),
                        (logMessage + "\n").getBytes(),
                        StandardOpenOption.APPEND);
            } catch (IOException e) {
                logger.error("Failed to write to log file", e);
            }
        }
    }


