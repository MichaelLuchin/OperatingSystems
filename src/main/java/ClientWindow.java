    private void sendMessage() {
        String input = jTextField1.getText().trim();

        if (input.isEmpty()) {
            return;
        }

        if (input.equalsIgnoreCase("exit")) {
            logAction("Closing connection and exiting");
            closeConnection();
            dispose();
            return;
        }

        try {
            logAction("Sending to server: " + input);

            out.println(input);

            String response = in.readLine();
            if (response != null) {
                logAction("Server response: " + response);
            }

            jTextField1.setText("");
        } catch (IOException e) {
            logError("Communication error: " + e.getMessage());
        }
    }

    private void closeConnection() {
        try {
            if (out != null) out.close();
            if (in != null) in.close();
            if (socket != null) socket.close();
            logAction("Connection closed");
        } catch (IOException e) {
            logError("Error closing connection: " + e.getMessage());
        }
    }

    @Override
    public void dispose() {
        closeConnection();
        super.dispose();
    }

