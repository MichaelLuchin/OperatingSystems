    private static void handleClient(Socket clientSocket, int clientId) {
        try (BufferedReader in = new BufferedReader(new InputStreamReader(clientSocket.getInputStream()));
             PrintWriter out = new PrintWriter(clientSocket.getOutputStream(), true)) {

            String inputLine;
            while ((inputLine = in.readLine()) != null) {
                try {
                    logMessage("Received from client #" + clientId + ": " + inputLine);
                    String result = calculateExpression(inputLine);
                    String response = "Result: " + result;
                    out.println(response);
                    logMessage("Sent to client #" + clientId + ": " + response);
                } catch (IllegalArgumentException e) {
                    String error = "Error: " + e.getMessage();
                    out.println(error);
                    logError("Error processing client #" + clientId + " input: " + e.getMessage());
                }
            }
        } catch (IOException e) {
            logError("Error handling client #" + clientId + ": " + e.getMessage());
        } finally {
            try {
                clientSocket.close();
                semaphore.release();
                clientCount--;
                logMessage("Client #" + clientId + " disconnected. Current clients: " + clientCount);
            } catch (IOException e) {
                logError("Error closing socket for client #" + clientId + ": " + e.getMessage());
            }
        }
    }

    private static String calculateExpression(String expression) {
        String cleaned = expression.replaceAll("\\s+", "");

        int opPos = findOperatorPosition(cleaned);
        if (opPos == -1 || opPos == 0 || opPos == cleaned.length() - 1) {
            throw new IllegalArgumentException("Invalid input format - operator not found or misplaced");
        }

        try {
            double num1 = Double.parseDouble(cleaned.substring(0, opPos));
            double num2 = Double.parseDouble(cleaned.substring(opPos + 1));
            char op = cleaned.charAt(opPos);

            double result = calculate(num1, num2, op);
            return String.valueOf(result);
        } catch (NumberFormatException e) {
            throw new IllegalArgumentException("Invalid numbers format");
        }
    }

    private static int findOperatorPosition(String str) {
        for (int i = 0; i < str.length(); i++) {
            char c = str.charAt(i);
            if (c == '+' || c == '-' || c == '*' || c == '/') {
                if (i == 0 && c == '-') continue;
                return i;
            }
        }
        return -1;
    }

    private static double calculate(double a, double b, char op) {
        switch (op) {
            case '+': return a + b;
            case '-': return a - b;
            case '*': return a * b;
            case '/':
                if (b == 0) throw new IllegalArgumentException("Division by zero");
                return a / b;
            default: throw new IllegalArgumentException("Invalid operator: " + op);
        }
    }

