    private void startServer() {
        new Thread(() -> {
            try (ServerSocket serverSocket = new ServerSocket(PORT)) {
                logMessage("Server started. Waiting for connections...");

                while (true) {
                    Socket clientSocket = serverSocket.accept();

                    try {
                        semaphore.acquire();
                        clientCount++;
                        int clientId = clientCount;
                        logMessage("Client #" + clientId + " connected. Current clients: " + clientCount);

                        new Thread(() -> handleClient(clientSocket, clientId)).start();
                    } catch (InterruptedException e) {
                        logError("Semaphore error: " + e.getMessage());
                        clientSocket.close();
                    }
                }
            } catch (IOException e) {
                logError("Server error: " + e.getMessage());
            }
        }).start();
    }

    public static void logMessage(String message) {
        String timestamp = LocalDateTime.now().format(dtf);
        String logMessage = timestamp + " - " + message;

        if (instance != null) {
            SwingUtilities.invokeLater(() -> {
                instance.jTextArea1.append(logMessage + "\n");
                instance.jTextArea1.setCaretPosition(instance.jTextArea1.getDocument().getLength());
            });
        }

        System.out.println(logMessage);

        if (instance != null && instance.logToFile) {
            try {
                Files.write(Paths.get(LOG_FILE),
                        (logMessage + "\n").getBytes(),
                        StandardOpenOption.CREATE,
                        StandardOpenOption.APPEND);
            } catch (IOException e) {
                System.err.println("Failed to write to log file: " + e.getMessage());
            }
        }
    }

